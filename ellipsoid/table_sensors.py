"""
table_sensors.py
----------------
Table 4: Case 2 (fibrosis) with 64, 32 and 16 measurement points.

Collects, for each UQ run, the files written by uq_regions.py and uq_qoi.py
(nothing is recomputed):

    <root>/<case>/regions_<case>.json   MAP error per region, mean posterior std of m
    <root>/<case>/qoi_<case>.json       geometric-mean core stiffness, 95 % interval

Usage (from the repository root):
    python -m ellipsoid.table_sensors \\
        --runs results/ellipsoid/uq:64 results/ellipsoid/uq_s32:32 results/ellipsoid/uq_s16:16

Writes <out>.tex (default results/ellipsoid/table_sensors.tex) and prints the table.
"""

import argparse
import json
from pathlib import Path


def load_run(root, case):
    d = Path(root) / case
    reg = json.load(open(d / f"regions_{case}.json"))["stats"]
    qoi = json.load(open(d / f"qoi_{case}.json"))["qoi"]["core"]
    p = qoi["posterior"]
    return dict(err_core=100 * reg["core"]["C_rel_L2"],
                err_healthy=100 * reg["healthy"]["C_rel_L2"],
                post_std=reg["all"]["post_std"],
                c_mean=p["mean"], c_lo=p["q025"], c_hi=p["q975"],
                c_truth=qoi["truth"])


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", nargs="+", required=True, metavar="ROOT:N",
                    help="UQ output folders and their number of measurement points")
    ap.add_argument("--case", default="fibrosis")
    ap.add_argument("--out", default="results/ellipsoid/table_sensors")
    a = ap.parse_args()

    runs = []
    for item in a.runs:
        root, n = item.rsplit(":", 1)
        runs.append((int(n), load_run(root, a.case)))

    rows = [("MAP error, core [\\%]", lambda r: f"{r['err_core']:.1f}"),
            ("MAP error, healthy [\\%]", lambda r: f"{r['err_healthy']:.1f}"),
            ("Posterior std of $m$", lambda r: f"{r['post_std']:.2f}"),
            ("$\\bar C_{\\mathrm{core}}$ [kPa]",
             lambda r: f"${r['c_mean']:.2f}\\,[{r['c_lo']:.2f},\\,{r['c_hi']:.2f}]$")]

    # console
    print(f"{'':28}" + "".join(f"{n:>22} points" for n, _ in runs))
    for label, fmt in rows:
        plain = label.replace("\\%", "%").replace("$", "").replace("\\bar C_{\\mathrm{core}}", "C_core")
        print(f"{plain:28}" + "".join(f"{fmt(r).replace('$', '').replace(chr(92) + ',', ' '):>29}"
                                       for _, r in runs))

    # LaTeX
    L = [r"\begin{table}[htbp]", r"\centering",
         r"\caption{Case~2 (fibrosis) with " + ", ".join(str(n) for n, _ in runs[:-1])
         + f" and {runs[-1][0]} measurement points (0\\% noise, same prior). Relative "
         r"$L^2$ error of the MAP estimate in the core ($r\le5$~mm) and in the healthy "
         r"tissue ($r\ge10$~mm), mean posterior standard deviation of $m=\ln C$, and "
         r"posterior mean and 95\% credible interval of the geometric-mean core stiffness "
         f"(truth {runs[0][1]['c_truth']:.0f}~kPa).}}",
         r"\label{tab:sensors}",
         r"\begin{tabular}{l" + "c" * len(runs) + "}", r"\toprule",
         " & " + " & ".join(f"{n} points" for n, _ in runs) + r" \\", r"\midrule"]
    for label, fmt in rows:
        L.append(label + " & " + " & ".join(fmt(r) for _, r in runs) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    out = Path(a.out).with_suffix(".tex")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("% Generated by table_sensors.py -- needs \\usepackage{booktabs}\n"
                   + "\n".join(L) + "\n")
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
