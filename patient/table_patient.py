"""
table_patient.py
----------------
Table 5: MAP estimate of Case 3 (patient LV) by inexact Newton-CG, from
<root>/metrics_lv_patient.json written by map_estimate.py (nothing is recomputed).

Usage (from the repository root):
    python -m patient.table_patient --root results/patient/map

Writes <out>.tex (default results/patient/table_patient.tex) and prints the table.
"""

import argparse
import json
from pathlib import Path


def sci(x):
    mant, exp = f"{x:.1e}".split("e")
    return f"${mant}\\times10^{{{int(exp)}}}$"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default="results/patient/map")
    ap.add_argument("--out", default="results/patient/table_patient")
    a = ap.parse_args()

    d = json.load(open(Path(a.root) / "metrics_lv_patient.json"))
    m, s = d["newtoncg"], d["settings"]
    rows = [
        ("Newton iterations / forward solves / Hessian actions",
         f"{m['n_iter']} / {m['n_forward']} / {m['n_hessvec']}"),
        ("Wall time [s]", f"{m['wall_time_s']:.0f}"),
        ("Final $\\|G\\|_\\infty$", sci(m["proj_grad_inf"])),
        ("Relative misfit in $\\mathbf{F}$", sci(m["F_rel_frob"])),
        ("Relative $L^2$ error of $C$: whole LV / fibrosis / healthy [\\%]",
         f"{100 * m['C_rel_L2']:.1f} / {100 * m['C_rel_L2_fibrosis']:.1f} / "
         f"{100 * m['C_rel_L2_healthy']:.1f}"),
        ("Mean $C$, MAP (truth) [kPa]: fibrosis / healthy",
         f"{m['C_mean_est_fibrosis']:.2f} ({m['C_mean_true_fibrosis']:.2f}) / "
         f"{m['C_mean_est_healthy']:.2f} ({m['C_mean_true_healthy']:.2f})"),
    ]

    for label, val in rows:
        plain = (label.replace("$", "").replace("\\|G\\|_\\infty", "||G||_inf")
                 .replace("\\mathbf{F}", "F").replace("\\%", "%"))
        print(f"  {plain:<62} {val.replace('$', '').replace(chr(92) + 'times10^', 'e').replace('{', '').replace('}', '')}")
    print(f"  (stop: {m['stop_reason']})")

    L = [r"\begin{table}[htbp]", r"\centering",
         f"\\caption{{Case~3 (patient LV): MAP estimate by inexact Newton-CG "
         f"({s['n_measurement_points']} measurement points, $p_{{\\mathrm{{endo}}}} = "
         f"{abs(s['load']):g}$~kPa, {100 * s['data_noise']:g}\\% noise, prior with "
         f"$k = {s['order']}$).}}",
         r"\label{tab:case3_map}", r"\begin{tabular}{lr}", r"\toprule"]
    L += [f"{label} & {val} \\\\" for label, val in rows]
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    out = Path(a.out).with_suffix(".tex")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("% Generated by table_patient.py -- needs \\usepackage{booktabs}\n"
                   + "\n".join(L) + "\n")
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
